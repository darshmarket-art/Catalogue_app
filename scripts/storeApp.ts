// Helpers for the per-store Android build (see scripts/build-store-app.ts and docs/android-addon.md): the config values are pure,
// the icon and Android-shell functions at the bottom write into the generated android/ folder.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

/** com.antarixs.<store>: lowercase letters/digits only; every Java package segment must start with a letter. */
export function appIdFor(storeId: string): string {
  const s = storeId.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!s) throw new Error(`Cannot make an app id from "${storeId}"`);
  return `com.antarixs.${/^[0-9]/.test(s) ? 's' + s : s}`;
}

/** Store id as used in URLs and merchants/<id>; same rule as server/merchant.ts. */
export const validStoreId = (id: string) => /^[a-z0-9-]{2,40}$/.test(id);

/** Accepts the live GET /api/config body ({data: merchant}), a store export ({store:{merchant}}) or a bare merchant. */
export function merchantFrom(json: any): any {
  const m = json?.data ?? json?.store?.merchant ?? json?.merchant ?? json;
  if (!m?.brand?.name) throw new Error('No merchant/brand found in the store data');
  return m;
}

/** Everything the native build needs, derived from the store's merchant config. */
export function nativeBuildValues(storeId: string, merchant: any, apiBase: string) {
  if (!validStoreId(storeId)) throw new Error(`Invalid store id "${storeId}"`);
  const colors = merchant.theme?.colors ?? {};
  return {
    appId: appIdFor(storeId),
    appName: String(merchant.brand.name),
    env: { MERCHANT: storeId, VITE_STORE: storeId, VITE_API_BASE: apiBase.replace(/\/+$/, '') },
    themeColor: colors.surface ?? '#f7f1e8',
    splashColor: colors.surface ?? '#f7f1e8',
    logoUrl: merchant.brand.logoUrl as string | undefined
  };
}

/** The merchants/<id>/merchant.json the existing build reads: the store's own config with the generated app id. */
export const merchantFileFor = (storeId: string, merchant: any) => ({
  ...merchant,
  id: storeId,
  android: { ...(merchant.android ?? {}), packageName: appIdFor(storeId), sha256CertFingerprints: merchant.android?.sha256CertFingerprints ?? [] }
});

/** Launcher icon sizes (px) per Android density folder. */
export const LAUNCHER_SIZES: Record<string, number> = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

/** Adaptive icon (Android 8+): layers are 108dp, a mask shows about 72dp, and the centre 66dp is never clipped. */
export const ADAPTIVE_DP = { canvas: 108, visible: 72, safe: 66 };
/** Adaptive layer sizes (px): 108dp per density, so 48dp * 2.25. */
export const ADAPTIVE_SIZES: Record<string, number> = Object.fromEntries(Object.entries(LAUNCHER_SIZES).map(([d, px]) => [d, px * 2.25]));

/** Foreground layer: `art` fitted inside a square of `boxDp` at the centre of a transparent 108dp canvas (`canvasPx` wide). */
export async function adaptiveForeground(art: Buffer, canvasPx: number, boxDp = ADAPTIVE_DP.safe): Promise<Buffer> {
  const box = Math.floor((canvasPx * boxDp) / ADAPTIVE_DP.canvas);
  const fitted = await sharp(art).resize(box, box, { fit: 'inside' }).png().toBuffer();
  return sharp({ create: { width: canvasPx, height: canvasPx, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite([{ input: fitted }]).png().toBuffer();
}

/** A logo's top-left colour, as the adaptive icon's background: a flat tile blends in, a transparent corner gives white (like the legacy icons). */
export async function cornerColor(img: Buffer): Promise<string> {
  const { data } = await sharp(img).flatten({ background: '#ffffff' }).extract({ left: 0, top: 0, width: 1, height: 1 }).raw().toBuffer({ resolveWithObject: true });
  return '#' + [...data.subarray(0, 3)].map((v) => v.toString(16).padStart(2, '0')).join('');
}

const HEX_COLOR = /^#([0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
/** Store colours come from the owner's config and are written into Android XML, so only a plain hex colour gets through. */
export const safeColor = (c: unknown, fallback: string) => (typeof c === 'string' && HEX_COLOR.test(c.trim()) ? c.trim() : fallback);

/** The adaptive icon: foreground layers per density plus the background colour. The template's mipmap-anydpi-v26 xml already points at both. */
export async function writeAdaptiveIcon(res: string, art: Buffer, background: string, boxDp = ADAPTIVE_DP.safe) {
  for (const [d, px] of Object.entries(ADAPTIVE_SIZES)) fs.writeFileSync(path.join(res, `mipmap-${d}`, 'ic_launcher_foreground.png'), await adaptiveForeground(art, px, boxDp));
  fs.writeFileSync(path.join(res, 'values/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${safeColor(background, '#ffffff')}</color>\n</resources>\n`);
}

// ---- Android shell patches (the project is generated by `npx cap add android`, so CI re-applies them every build; each is safe to run twice) ----

/** Night-mode ground, the same as the boot splash in index.html. */
export const NIGHT_GROUND = '#180e14';

/** Soft keyboard: adjustResize on the activity (the template sets none, so Android guesses). */
export function patchManifest(xml: string): string {
  if (xml.includes('android:windowSoftInputMode')) return xml;
  return xml.replace('android:name=".MainActivity"', 'android:name=".MainActivity"\n            android:windowSoftInputMode="adjustResize"');
}

/** Window and launch background from the app's own ground colour instead of the template's white splash image. */
export function patchStyles(xml: string): string {
  if (xml.includes('splash_bg')) return xml;
  return xml
    .replace('<item name="android:background">@null</item>', '$&\n        <item name="android:windowBackground">@color/splash_bg</item>')
    .replace('<item name="android:background">@drawable/splash</item>', '<item name="android:background">@color/splash_bg</item>\n        <item name="windowSplashScreenBackground">@color/splash_bg</item>');
}

/** MainActivity that draws edge to edge on every Android version (15+ forces it anyway); Capacitor's SystemBars then supplies the insets. */
export const mainActivityJava = (pkg: string) => `package ${pkg};

import android.os.Bundle;
import androidx.activity.EdgeToEdge;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        EdgeToEdge.enable(this);
        super.onCreate(savedInstanceState);
    }
}
`;

/** Applies the shell patches to the generated android/ folder: keyboard, edge to edge, splash and window colour. */
export function patchAndroidShell(androidDir: string, ground: string, night = NIGHT_GROUND) {
  const main = path.join(androidDir, 'app/src/main');
  const res = path.join(main, 'res');
  const edit = (file: string, fn: (s: string) => string, done: string) => {
    const was = fs.readFileSync(file, 'utf8');
    const now = fn(was);
    if (!now.includes(done)) console.warn(`Android shell: ${path.relative(androidDir, file)} did not match the template, "${done}" not applied.`);
    else if (now !== was) fs.writeFileSync(file, now);
  };
  edit(path.join(main, 'AndroidManifest.xml'), patchManifest, 'adjustResize');
  edit(path.join(res, 'values/styles.xml'), patchStyles, '@color/splash_bg');
  const colorXml = (c: string) => `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="splash_bg">${c}</color>\n</resources>\n`;
  fs.mkdirSync(path.join(res, 'values-night'), { recursive: true });
  fs.writeFileSync(path.join(res, 'values/splash_bg.xml'), colorXml(safeColor(ground, '#f7f1e8')));
  fs.writeFileSync(path.join(res, 'values-night/splash_bg.xml'), colorXml(safeColor(night, NIGHT_GROUND)));
  for (const d of fs.readdirSync(res).filter((n) => n.startsWith('drawable'))) {
    fs.rmSync(path.join(res, d, 'splash.png'), { force: true }); // the template's white Capacitor splash image
    if (!fs.readdirSync(path.join(res, d)).length) fs.rmdirSync(path.join(res, d));
  }
  const activity = (fs.readdirSync(path.join(main, 'java'), { recursive: true }) as string[]).find((f) => f.endsWith('MainActivity.java'));
  if (!activity) return console.warn('Android shell: MainActivity.java not found.');
  const file = path.join(main, 'java', activity);
  const src = fs.readFileSync(file, 'utf8');
  const pkg = /^package\s+([\w.]+);/m.exec(src)?.[1];
  if (src.includes('EdgeToEdge')) return;
  if (!pkg || !/public class MainActivity extends BridgeActivity \{\s*\}/.test(src)) return console.warn('Android shell: MainActivity.java was changed from the template, edge-to-edge not applied.');
  fs.writeFileSync(file, mainActivityJava(pkg));
}
